CNI_PE_HISTORY_FILE = Path(__file__).resolve().parent.parent / "data" / "cni_pe_history.csv"


@st.cache_data(ttl=3600, show_spinner=False)
def _cni_pe_history() -> pd.DataFrame:
    """The bundled daily P/E history for the CNI indices (date, code, pe).
    Read once per hour; an unreadable/missing file yields an empty frame and
    the affected rows simply show '-' in the median column."""
    try:
        df = pd.read_csv(CNI_PE_HISTORY_FILE, dtype={"code": str}, parse_dates=["date"])
        df = df.dropna(subset=["pe"])[["date", "code", "pe"]]
        return df if df is not None else pd.DataFrame()
    except Exception:
        return pd.DataFrame()


def _cnindex_pe_history_median(code: str) -> Optional[float]:
    """Median of the reconstructed daily P/E over the last 5 years of the
    bundled history (or the whole file if it is younger). < MEDIAN_MIN_OBS
    observations -> None (the row shows '-')."""
    hist = _cni_pe_history()
    if hist.empty:
        return None
    code = str(code).strip()
    s = hist[hist["code"] == code].sort_values("date")
    if s.empty:
        return None
    window_start = pd.Timestamp.now() - pd.Timedelta(days=365 * MEDIAN_YEARS)
    s = s[s["date"] >= window_start]
    if len(s) < MEDIAN_MIN_OBS:
        return None
    return float(s["pe"].median())


