"""
Index valuation: P/E (TTM) + 5-year median for the benchmark indices and
strategies shown at the bottom of the dashboard.

Most rows come STRAIGHT from official sources with live queries
(no own calculations, a handful of fast HTTP requests, ~3-5 s total):
- CSI indices (000300, 931071, H30015, 000852, 930939, 931052): official
  csindex.com.cn API. The `peg` field of /csindex-home/perf/index-perf is the
  rolling P/E (TTM), published daily after the close. The same endpoint also
  serves the full daily history, which is where the 5-year median comes from.
- CNI / SZSE indices (980017, 980022, 980018, 399266): official cnindex.com.cn
  API (POST /index/search). The `peDynamic` field is exactly the number that
  cnindex.com.cn itself displays in its index table under "PE(滚动)"
  (rolling P/E).
- Hang Seng TECH: Danjuan (Xueqiu) index valuation service.

The composite strategy "Новая энергетика Китая" (ETFs 159326 + 159009 +
562960) is computed as a weighted portfolio of its three underlying indices:
P/E = 1 / sum(w_i / PE_i) (aggregate earnings yield of the blend). Weights
are read from the user's portfolio with the same name in Google Sheets when
it exists, otherwise the three ETFs are weighted equally.

The two remaining Hang Seng indices (High Dividend Low Vol, Biotech) have no
free official P/E feed, so they are COMPUTED - but only once per day:
P/E = sum(total market cap) / sum(TTM earnings) over the full holdings of
their tracker ETFs (159545 / 159892, Eastmoney F10 semi-annual reports),
using Tencent gtimg per-stock P/E TTM. Loss-makers are included (they reduce
the aggregate earnings) - the same convention Wind/Danjuan use. ~1-2 s.

5-YEAR MEDIAN, four mechanisms (in this priority order):
(a) Wind overrides - median P/E values that the user pastes BY HAND into the
    `wind_medians` tab of the Google Sheet (key | median_pe | note). `key` is
    either a row key of INDEX_PE_CONFIG ('semi', 'new_energy', 'hk_tech', ...)
    or an index / ETF code ('399266', '980017', '159545', '000300'). Works for
    every row and overrides anything else.
(b) CSI rows (and the CSI parts of the composite) - the median of the OFFICIAL
    daily P/E history from csindex (one request per index). The two composite
    CSI parts are young indices - 931994 exists since 2022-09, 931897 since
    2022-04 - so their median is computed over the window that exists.
(c) CNI rows (980017, 980022, 980018) and the 399266 part of the composite:
    cnindex.com.cn publishes no free P/E history (verified 2026-11-24 - only the
    current PE(滚动) and OHLCV-only daily files), so a 5-year daily P/E history
    is reconstructed OFFLINE and bundled with the app as
    `data/cni_pe_history.csv` (generated by tools/compute_cni_pe_history.py):
      - membership timeline: official cnindex `download-adjustment` records;
      - per-stock P/E (TTM): BaoStock peTTM (exact daily, matches the exchange);
      - per-stock total market cap: Baidu gushitong, anchored per stock to the
        cnindex A-share market cap (removes the A+H combined cap of
        dual-listed members such as SMIC);
      - aggregate: P/E = sum(mcap) / sum(mcap/pe) over profitable members - the
        convention locked by matching the official current peDynamic of all
        four indices on the same day (mean error +0.8%; including loss-makers
        gives +43%, zeroing their earnings +15%).
    The last computed day reproduces the official P/E within ~1.5%. Refresh =
    re-run tools/compute_cni_pe_history.py (no Wind needed).
(d) Hang Seng rows (hk_tech, hk_bio, hk_div): no free official P/E history
    exists either (hsi.com.hk factsheets are overwritten monthly with no
    archive; Danjuan's history API needs a phone login and covers only
    HKHSTECH), so a 5-year daily P/E history is likewise reconstructed OFFLINE
    and bundled as `data/hk_pe_history.csv` (generated by
    tools/compute_hk_pe_history.py):
      - membership timeline: full holdings of the tracker ETFs (513180 /
        159892 / 159545) from their semi-annual reports - the same ETF-proxy
        the live P/E of these rows uses; before an ETF's first full report the
        first known list is backcast (159545 exists since 2024-03, so the
        HSHYLV membership is backcast ~2.5 years);
      - per-stock P/E (TTM) and total market cap: Baidu gushitong (its
        last-day values match the Tencent gtimg quotes of the live column
        exactly);
      - market caps extended to every trading day with the Tencent ifzq close;
      - aggregate: P/E = Σ mcap / Σ earnings with loss-makers INCLUDED - the
        exact convention of the live column of these rows.
    The last computed day reproduces the live aggregate within ~1-2%. Refresh
    = re-run tools/compute_hk_pe_history.py (no Wind needed).
The composite row blends its parts' medians with the same portfolio formula
as its P/E (1 / sum(w_i / median_i)); if any part's median is unknown, it
shows "-" as well.
Daily P/E snapshots keep accumulating in `pe_cache` exactly as before
(append-only). They are no longer turned into a displayed "median" - a
2-week "median" was misleading (it sat below the current P/E whenever the
sector rallied within the observation window) - but they keep building a
genuine history.
Danjuan's published pe_percentile (share of the index's whole history that
lies ABOVE the current P/E) is still fetched for Hang Seng TECH and kept in
the dataframe for reference; the UI does not render it anymore.

A snapshot of every value is appended (append-only, dedup by day) to the
`pe_cache` tab of the Google Sheet for the last completed trading day.
get_pe_table() serves that snapshot whenever it already exists, so the live
sources are normally hit only once per day, after the 17:30 cache refresh.

Empirical data-format notes (verified):
- Tencent gtimg quotes: for HK stocks the P/E TTM is field 57 (field 39 is
  the dynamic P/E there); field 45 is total market cap. Requests accept
  ~50 symbols at once and answer in <0.1 s.
- Eastmoney FundArchivesDatas.aspx REQUIRES a Referer header from
  fundf10.eastmoney.com, otherwise it returns an empty payload.
"""
